-- 1. create Table for University 
CREATE TABLE University (
    University_ID VARCHAR(10) PRIMARY KEY,
    University_Name VARCHAR(150) NOT NULL,
    Country VARCHAR(100) NOT NULL,
    International_Ranking INT,
    Accreditation_Status VARCHAR(100),
    Year_of_Establishment INT NOT NULL
);
-- 2. create Table for College
CREATE TABLE College (
    College_ID VARCHAR(10) PRIMARY KEY,
    College_Name VARCHAR(150) NOT NULL,
    Head_of_College VARCHAR(100),
    Location VARCHAR(200),
    University_ID VARCHAR(10) NOT NULL,
    FOREIGN KEY (University_ID) REFERENCES University(University_ID)
        ON DELETE CASCADE ON UPDATE CASCADE
);
-- 3. create Table for Department
CREATE TABLE Department (
    Department_ID VARCHAR(10) PRIMARY KEY,
    Department_Name VARCHAR(150) NOT NULL,
    Specialization_Field VARCHAR(100),
    Office_Location VARCHAR(200),
    Contact_Email VARCHAR(100),
    College_ID VARCHAR(10) NOT NULL,
    FOREIGN KEY (College_ID) REFERENCES College(College_ID)
        ON DELETE CASCADE ON UPDATE CASCADE
);
-- 4. create Table for Researcher
CREATE TABLE Researcher (
    Researcher_ID VARCHAR(10) PRIMARY KEY,
    Full_Name VARCHAR(100) NOT NULL,
    Nationality VARCHAR(50),
    Date_of_Birth DATE,
    Gender CHAR(1) CHECK (Gender IN ('M', 'F')),
    Institutional_Email VARCHAR(100) UNIQUE,
    ORCID VARCHAR(20) UNIQUE,
    Academic_Rank VARCHAR(50),
    Start_Date DATE,
    Contract_Type VARCHAR(30),
    Experience_Years INT,
    Department_ID VARCHAR(10) NOT NULL,
    FOREIGN KEY (Department_ID) REFERENCES Department(Department_ID)
        ON DELETE CASCADE ON UPDATE CASCADE
);
-- 5. create Table for Research_Center
CREATE TABLE Research_Center (
    Center_ID VARCHAR(10) PRIMARY KEY,
    Center_Name VARCHAR(150) NOT NULL,
    Research_Focus_Area VARCHAR(100),
    Annual_Budget DECIMAL(12,2),
    Establishment_Date DATE,
    Director_ID VARCHAR(10),
    Department_ID VARCHAR(10) NOT NULL,
    FOREIGN KEY (Director_ID) REFERENCES Researcher(Researcher_ID)
        ON DELETE SET NULL ON UPDATE CASCADE,
    FOREIGN KEY (Department_ID) REFERENCES Department(Department_ID)
        ON DELETE CASCADE ON UPDATE CASCADE
);
-- 6. create Table for Researcher_Specialization
CREATE TABLE Researcher_Specialization (
    Researcher_ID VARCHAR(10),
    Specialization VARCHAR(100),
    PRIMARY KEY (Researcher_ID, Specialization),
    FOREIGN KEY (Researcher_ID) REFERENCES Researcher(Researcher_ID)
        ON DELETE CASCADE ON UPDATE CASCADE
);
-- 7. create Table for Project
CREATE TABLE Project (
    Project_ID VARCHAR(10) PRIMARY KEY,
    Project_Title VARCHAR(200) NOT NULL,
    Abstract TEXT,
    Research_Domain VARCHAR(100),
    Start_Date DATE,
    End_Date DATE,
    Total_Budget DECIMAL(12,2),
    Status VARCHAR(20) CHECK (Status IN ('Proposed', 'Active', 'Completed')),
    Center_ID VARCHAR(10) NOT NULL,
    FOREIGN KEY (Center_ID) REFERENCES Research_Center(Center_ID)
        ON DELETE CASCADE ON UPDATE CASCADE
);
-- 8. create Table for Project_Assignment
CREATE TABLE Project_Assignment (
    Researcher_ID VARCHAR(10),
    Project_ID VARCHAR(10),
    Role VARCHAR(50),
    Contribution VARCHAR(10),
    PRIMARY KEY (Researcher_ID, Project_ID),
    FOREIGN KEY (Researcher_ID) REFERENCES Researcher(Researcher_ID)
        ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (Project_ID) REFERENCES Project(Project_ID)
        ON DELETE CASCADE ON UPDATE CASCADE
);
